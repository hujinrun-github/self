CREATE TABLE journal_notebooks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  public_title TEXT NOT NULL DEFAULT '',
  cover_color TEXT NOT NULL DEFAULT '#d9e5ee',
  paper TEXT NOT NULL DEFAULT 'plain' CHECK (paper IN ('plain','ruled','dots')),
  public_enabled BOOLEAN NOT NULL DEFAULT false,
  archived BOOLEAN NOT NULL DEFAULT false,
  password_hash TEXT NOT NULL DEFAULT '',
  password_version BIGINT NOT NULL DEFAULT 1,
  version BIGINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (NOT public_enabled OR (password_hash <> '' AND NOT archived AND public_title <> ''))
);
CREATE TABLE journal_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notebook_id BIGINT NOT NULL REFERENCES journal_notebooks(id) ON DELETE RESTRICT,
  title TEXT NOT NULL DEFAULT '',
  entry_date DATE NOT NULL,
  mood TEXT NOT NULL DEFAULT '',
  weather TEXT NOT NULL DEFAULT '',
  tags JSONB NOT NULL DEFAULT '[]',
  favorite BOOLEAN NOT NULL DEFAULT false,
  scene JSONB NOT NULL,
  search_text TEXT NOT NULL DEFAULT '',
  version BIGINT NOT NULL DEFAULT 1,
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, notebook_id)
);
CREATE INDEX journal_entries_notebook_date ON journal_entries (notebook_id, entry_date DESC, id DESC);
CREATE INDEX journal_entries_trash ON journal_entries (deleted_at) WHERE deleted_at IS NOT NULL;
CREATE TABLE journal_assets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notebook_id BIGINT NOT NULL REFERENCES journal_notebooks(id) ON DELETE CASCADE,
  mime_type TEXT NOT NULL CHECK (mime_type IN ('image/jpeg','image/png')),
  width INTEGER NOT NULL CHECK (width > 0),
  height INTEGER NOT NULL CHECK (height > 0),
  file_name TEXT NOT NULL,
  size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
  data BYTEA NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, notebook_id)
);
CREATE TABLE journal_entry_assets (
  entry_id BIGINT NOT NULL,
  asset_id BIGINT NOT NULL,
  notebook_id BIGINT NOT NULL,
  PRIMARY KEY (entry_id, asset_id),
  FOREIGN KEY (entry_id, notebook_id) REFERENCES journal_entries(id, notebook_id) ON DELETE CASCADE,
  FOREIGN KEY (asset_id, notebook_id) REFERENCES journal_assets(id, notebook_id) ON DELETE RESTRICT
);
CREATE INDEX journal_entry_assets_asset ON journal_entry_assets(asset_id);
CREATE TABLE journal_view_sessions (
  token_hash TEXT PRIMARY KEY,
  notebook_id BIGINT NOT NULL REFERENCES journal_notebooks(id) ON DELETE CASCADE,
  password_version BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX journal_view_sessions_expiry ON journal_view_sessions(expires_at);
CREATE TABLE journal_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notebook_id BIGINT REFERENCES journal_notebooks(id) ON DELETE SET NULL,
  admin_id BIGINT REFERENCES admins(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
